#!/usr/bin/env python3
"""Generate md_names.h: the short names of the bank's sounds (from bank.json, as build_bank.py wrote it), for the pages.

    python3 tools/bank/gen_names.py > md_names.h

Lowercase, as the OP-1's own labels; at most 16 characters.
Copyright (C) 2026 Sammi (Project Medieval). GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE, NOTICE).
"""
import json
from pathlib import Path

sounds = json.loads((Path(__file__).resolve().parent / 'bank.json').read_text())['sounds']
print('/* md_names.h: generated by tools/gen_names.py from bank.json. Do not edit. */')
print(f'static const char md_name[{len(sounds)}][17] = {{')
for s in sounds:
    n = ' '.join(s['name'].lower().split())[:16]
    print(f'    "{n}",')
print('};')
