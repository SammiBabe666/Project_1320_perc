#include <stdio.h>
#include "p_voice.h"
#include "p_page.h"
int main(void)
{
    printf("/* p_peaks.h: generated by tools/gen_peaks.c from md_bank.h. Do not edit. */\n");
    printf("static const uint8_t p_peaks[%d][%d] = {\n", P_NSOUNDS, P_PEAKS);
    for (int s = 0; s < P_NSOUNDS; s++) {
        uint8_t pk[P_PEAKS];
        p_sound_peaks(s, pk, P_PEAKS);
        printf("    {");
        for (int i = 0; i < P_PEAKS; i++) printf("%s%d", i ? "," : " ", pk[i]);
        printf(" },\n");
    }
    printf("};\n");
    return 0;
}
