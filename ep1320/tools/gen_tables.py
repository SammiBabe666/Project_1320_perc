#!/usr/bin/env python3
"""Generate p_tables.h, the engine's fixed tables (the OP-1 has no floating point).

    python3 tools/gen_tables.py > p_tables.h

  P_FIR_INIT     playback interpolation, Q14: tap k of phase p weights source sample i + k - 7 for position i + p/64.
                 A Kaiser-windowed sinc (beta 5) cut at the source's Nyquist frequency, as medieval v0.2.3 used: the
                 bank is stored at 11.025-22.05 kHz and the engine resamples it to 44.1 kHz.
  p_decay[64]    gain factor per 64-sample block (44.1 kHz), Q15, for white (decay): index 0-62 fall 60 dB in 30 ms
                 to 3 s; 63 keeps the sound to its natural end.
  p_t60_ms[63]   those times in ms, for the page.
  p_exp2[257]    2^(i/256) in Q16: the pitch ratio of a fraction of an octave.
  P_IMA_DIFF_INIT, P_IMA_NEXT_INIT  the IMA ADPCM decoder as two tables, by step index x 8 + the nibble's low three
                 bits: the difference it adds (bit for bit the decoder's shifts and adds), and the next step index x 8.
  The last three are initialisers of p_tab_t (p_voice.h), the block the engine keeps in fast memory.
"""
import numpy as np


def arr(name, ctype, vals, per=8):
    rows = [', '.join(str(int(v)) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'static const {ctype} {name}[{len(vals)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def fir():
    taps, ph, beta = 16, 64, 5.0
    rows = []
    for p in range(ph):
        t = np.arange(taps) - (taps // 2 - 1) - p / ph
        w = np.i0(beta * np.sqrt(np.clip(1 - (t / (taps / 2)) ** 2, 0, 1))) / np.i0(beta)
        h = np.sinc(t) * w
        h = h / h.sum() * 16384
        r = np.round(h).astype(int)
        r[taps // 2 - 1 + (p >= ph // 2)] += 16384 - r.sum()     # each phase sums to exactly 1.0
        rows.append(r)
    return rows


print('/* p_tables.h: generated by tools/gen_tables.py. Do not edit. */')
print('#ifndef P_TABLES_H\n#define P_TABLES_H')
t60 = [0.03 * (3.0 / 0.03) ** (i / 62) for i in range(63)]
print(arr('p_decay', 'int32_t', [round(32768 * 10 ** (-3 * 64 / 44100 / t)) for t in t60] + [32768]))
print(arr('p_t60_ms', 'uint16_t', [round(t * 1000) for t in t60]))
print(arr('p_exp2', 'uint32_t', [round(65536 * 2 ** (i / 256)) for i in range(257)]))
STEP = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60, 66, 73, 80, 88, 97,
        107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371, 408, 449, 494, 544, 598, 658, 724, 796,
        876, 963, 1060, 1166, 1282, 1411, 1552, 1707, 1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871,
        5358, 5894, 6484, 7132, 7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623,
        27086, 29794, 32767]
IDX = [-1, -1, -1, -1, 2, 4, 6, 8]
diff, nxt = [], []
for i in range(89):
    st = STEP[i]
    for n in range(8):
        d = st >> 3
        if n & 1: d += st >> 2
        if n & 2: d += st >> 1
        if n & 4: d += st
        diff.append(d)
        nxt.append(min(88, max(0, i + IDX[n])) * 8)
def init(name, vals, per=16):                      # an initialiser for p_tab_t's member (p_voice.h)
    rows = [', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'#define {name} {{ \\\n    ' + ', \\\n    '.join(rows) + ' }\n'


print(init('P_IMA_DIFF_INIT', diff))                 # up to 1.875 x 32767: unsigned
print(init('P_IMA_NEXT_INIT', nxt))
print(init('P_FIR_INIT', ['{ ' + ', '.join(str(int(v)) for v in r) + ' }' for r in fir()], 1))
print('#endif')
